import assert from 'node:assert/strict';
import {inspectSaintLaurentSource,saintLaurentProductUrl} from '../crawler/common/saint-laurent-product.js';
const sku='A00FMUAAHXH1000',other='A00FMUAAHXH6178';
const url=`https://www.ysl.com/ko-kr/pr/fixture-${sku}.html`;
const image=`https://saint-laurent.dam.kering.com/asset/fixture/Medium/${sku}_A.jpg?v=1`;
const item={id:sku,name:'Fixture bag',url,salePriceValue:5210000,currencyCode:'KRW',image:{src:image},categories:{lvl0:['Bags'],lvl1:['Bags > Shoulder']}};
const script=value=>`<script>window.fixture = ${JSON.stringify(value)};</script>`;
const one=html=>inspectSaintLaurentSource(html).records[0];
const plain=one(script(item));assert.equal(plain.price,5210000);assert.equal(plain.currency,'KRW');assert.equal(plain.name,'Fixture bag');assert.deepEqual(plain.taxonomy,item.categories);assert.deepEqual(plain.images,[image]);assert.equal(plain.originalImageVerified,false);
const flight=`<script>self.__next_f.push([1,${JSON.stringify('7:'+JSON.stringify(item)+'\n')}]);</script>`;
assert.equal(one(flight).price,5210000);
const attribute=JSON.stringify(item).replaceAll('"','&quot;');assert.equal(one(`<div data-product="${attribute}"></div>`).sku,sku);
assert.equal(one(script({...item,currencyCode:'USD'})).price,null);
assert.equal(one(script({...item,currencyCode:undefined})).price,null);
assert.equal(one(script({...item,salePriceValue:null,salePrice:'₩5,210,000'})).price,null);
assert.equal(one(script({...item,salePriceValue:'5,210,000'})).price,null);
assert.equal(one(script([item,{...item,salePriceValue:1}])).price,null);
assert.equal(one(script([item,{...item,name:'Different'}])).name,null);
assert.equal(one(script({...item,image:{src:image.replace(sku,other)}})).images.length,0);
assert.equal(inspectSaintLaurentSource(script({...item,url:url.replace(sku,other)})+`<a href="${url}"></a>`).records.length,0);
assert.equal(saintLaurentProductUrl(url.replace('www.ysl.com','www.ysl.com.evil.invalid')),null);
assert.equal(saintLaurentProductUrl(url.replace('/ko-kr/','/en-us/')),null);
assert.equal(saintLaurentProductUrl(url+'?price=1'),null);
assert.equal(inspectSaintLaurentSource(`<a href="${url}">₩9,999,999</a>`).records.length,0);
inspectSaintLaurentSource('<script>globalThis.YSL_TEST_EXECUTED=true;</script>');assert.equal(globalThis.YSL_TEST_EXECUTED,undefined);
assert.throws(()=>inspectSaintLaurentSource('x'.repeat(8388609)),/LIMIT/);
const original=image.replace('/Medium/','/published-fixture-original/');
const evidence=inspectSaintLaurentSource(script({...item,media:{original:{url:original,width:2400,height:1800},zoom:{url:image},fullsize:{url:image.replace(sku,other)}}})+`<img srcset="${image} 320w, ${original} 2400w">`).imageEvidence;
assert.equal(evidence.length,2);assert.equal(evidence.find(i=>i.url===original).originalVerified,false);
assert.deepEqual(evidence.find(i=>i.url===original).declaredDimensions,['2400X1800']);
assert.deepEqual(evidence.find(i=>i.url===original).srcsetWidths,[2400]);
assert.ok(evidence.find(i=>i.url===original).kinds.includes('ORIGINAL_FIELD'));
assert.ok(evidence.find(i=>i.url===image).kinds.includes('ZOOM_FIELD'));
assert.equal(evidence.some(i=>i.url===image.replace('/Medium/','/')),false);
assert.deepEqual(evidence.find(i=>i.url===image).declaredDimensions,[]);
assert.equal(inspectSaintLaurentSource(script({...item,image:{src:image.replace('saint-laurent.dam.kering.com','evil.invalid')}})).imageEvidence.length,0);
console.log('PASS: YSL strict native/Flight JSON, explicit price/currency, taxonomy, exact image SKU, conflicts, unknowns, no evaluation/network');
