import assert from 'node:assert/strict';
import {inspectHermesListingEvidence as inspect,hermesEvidenceLink} from '../crawler/common/hermes-listing-evidence.js';
const sku='H073428CKO5',url=`https://www.hermes.com/kr/ko/product/fixture-${sku}/`;
const p={sku,url,name:'Fixture',category:'Explicit',offers:{price:1230000,priceCurrency:'KRW'}};
const script=v=>`<script type="application/ld+json">${JSON.stringify(v)}</script>`;
assert.equal(inspect(script(p)).records[0].price,1230000);
assert.equal(inspect(script({...p,offers:{price:1230000}})).records[0].price,null);
assert.equal(inspect(script({...p,offers:{price:'1,230,000',priceCurrency:'KRW'}})).records[0].price,null);
assert.equal(inspect(script({...p,offers:{price:12,priceCurrency:'USD'}})).records[0].price,null);
assert.equal(inspect(`<a href="${url}">₩ 1,230,000 bag</a>`).records.length,0);
assert.equal(inspect(script({...p,url:url.replace(sku,'H073428CK00')})).records.length,0);
assert.equal(inspect(script({...p,category:null})).records[0].taxonomy,null);
assert.deepEqual(inspect(script({...p,category:undefined,categories:[{name:'Explicit fixture category'}]})).records[0].taxonomy,[{name:'Explicit fixture category'}]);
const missing=inspect(script({currency:'KRW',products:[{...p,offers:undefined,price:1230000}]}));assert.equal(missing.records[0].price,null);assert.equal(missing.stats.krwCurrencyObjects,1);
assert.equal(inspect(`<div data-product='${JSON.stringify(p)}'></div>`).records[0].sku,sku);
assert.equal(inspect(`<script>window.fixture=${JSON.stringify(p)}</script>`).records[0].sku,sku);
assert.equal(inspect(script(p)).records[0].originalImageVerified,false);
assert.equal(hermesEvidenceLink(url.replace('www.hermes.com','evil.invalid')),null);
inspect('<script>globalThis.HERMES_EXECUTED=true</script>');assert.equal(globalThis.HERMES_EXECUTED,undefined);
assert.throws(()=>inspect('x'.repeat(8388609)),/LIMIT/);
console.log('PASS: Hermes exact typed metadata, strict currency, no visible-text inference, no evaluation');
