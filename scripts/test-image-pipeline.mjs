import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {originalImageUrl,IMAGE_PROCESSING_VERSION} from '../crawler/common/image-processor.js';
const root=path.resolve(import.meta.dirname,'..');
assert.equal(IMAGE_PROCESSING_VERSION,'original-cutout-v1');
assert.equal(originalImageUrl('https://www.prada.com/content/dam/a.jpg/_jcr_content/renditions/a.webp'),'https://www.prada.com/content/dam/a.jpg');
assert.throws(()=>originalImageUrl('https://example.com/a.jpg'));
assert.throws(()=>originalImageUrl('http://www.chanel.com/a.jpg'));
assert.throws(()=>originalImageUrl('https://www.prada.com/not-an-asset.jpg'));
const python=path.join(root,'.image-runtime/venv/bin/python'),worker=path.join(root,'crawler/common/cutout-worker.py'),model=path.join(root,'.image-runtime/u2net.onnx');
const isolated=spawnSync('/usr/bin/sandbox-exec',['-p','(version 1)(allow default)(deny network*)',python,'-I',worker,model],{input:'',encoding:'utf8',timeout:30000,env:{PATH:process.env.PATH}});
assert.equal(isolated.status,0);assert.equal(JSON.parse(isolated.stdout).ready,true);
const unisolated=spawnSync(python,['-I',worker,model],{input:'',encoding:'utf8',timeout:5000,env:{PATH:process.env.PATH}});
assert.equal(unisolated.status,78);assert.equal(JSON.parse(unisolated.stdout).code,'OFFLINE_RUNTIME_FAILED');
const wrongModel=spawnSync('/usr/bin/sandbox-exec',['-p','(version 1)(allow default)(deny network*)',python,'-I',worker,path.join(root,'crawler/guardrails.json')],{input:'',encoding:'utf8',timeout:30000,env:{PATH:process.env.PATH}});
assert.equal(wrongModel.status,78);
assert(!fs.readFileSync(path.join(root,'crawler/common/image-processor.js'),'utf8').includes('.trim('));
console.log('PASS: original source, no pre-crop, pinned offline worker, network-required rejection, checksum-required rejection');
